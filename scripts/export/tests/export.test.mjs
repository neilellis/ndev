test('an export refuses to overwrite a file that it did not generate, names it, and writes nothing', () => {
  const out = fresh()
  const mine = join(out, 'skills/ndev-work-light/SKILL.md')
  mkdirSync(dirname(mine), { recursive: true })
  writeFileSync(mine, 'my own skill')
  const ran = run(['codex', '--out', out, '--date', DATE])
  assert.equal(ran.status, 3, ran.stderr)
  assert.match(ran.stderr, new RegExp(mine.replaceAll('/', '\\/')))
  assert.match(ran.stderr, /Repair:/)
  assert.equal(readFileSync(mine, 'utf8'), 'my own skill')
  assert.ok(!existsSync(join(out, 'home')), 'nothing written')
})

test('a second export replaces its own files and removes those that the plugin no longer has', () => {
  const { out } = exported()
  const gone = join(out, 'skills/ndev-gone/SKILL.md')
  mkdirSync(dirname(gone), { recursive: true })
  writeFileSync(gone, 'from an older plugin')
  const manifestFile = join(out, 'home/manifest.json')
  const manifest = JSON.parse(readFileSync(manifestFile, 'utf8'))
  manifest.files.push(gone)
  writeFileSync(manifestFile, JSON.stringify(manifest))
  const ran = run(['codex', '--out', out, '--date', '2026-12-01T00:00:00.000Z'])
  assert.equal(ran.status, 0, ran.stderr)
  assert.ok(!existsSync(gone))
  assert.ok(!existsSync(dirname(gone)), 'the empty folder goes too')
  assert.match(readFileSync(join(out, 'skills/ndev-work-light/SKILL.md'), 'utf8'), /on 2026-12-01T00:00:00\.000Z\./)
})

test('the summary lists the Claude-only constructs left for the adapter, and the full list is in the home', () => {
  const { out, summary } = exported()
  const full = JSON.parse(readFileSync(join(out, 'home/leftovers.json'), 'utf8'))
  assert.ok(Array.isArray(full) && full.length > 0)
  for (const item of full) {
    assert.ok(existsSync(item.file), item.file)
    assert.ok(Number.isInteger(item.line) && item.line > 0)
    assert.equal(typeof item.construct, 'string')
  }
  assert.equal(summary.leftovers.total, full.length)
  assert.equal(summary.leftovers.file, join(out, 'home/leftovers.json'))
})

