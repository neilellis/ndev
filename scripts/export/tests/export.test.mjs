test('a write that fails names the path and the repair, and the export runs again once the path is clear', () => {
  const out = fresh()
  mkdirSync(join(out, 'home'), { recursive: true })
  writeFileSync(join(out, 'home/kb'), 'a file where a folder goes')
  const failed = run(['codex', '--out', out, '--date', DATE])
  assert.equal(failed.status, 1, failed.stderr)
  assert.match(failed.stderr, new RegExp(`${join(out, 'home/kb')}`))
  assert.match(failed.stderr, /Repair:/)
  assert.doesNotMatch(failed.stderr, /^\s+at /m, 'no stack trace')
  rmSync(join(out, 'home/kb'))
  const again = run(['codex', '--out', out, '--date', DATE])
  assert.equal(again.status, 0, again.stderr)
})

test('the removal of old files keeps the export folders and the folders above them', () => {
  const base = fresh()
  const user = join(base, 'user')
  const common = ['--agents-dir', join(base, 'agents'), '--home', join(base, 'home'), '--date', DATE]
  assert.equal(run(['codex', '--skills-dir', join(user, 'skills'), ...common]).status, 0)
  const moved = run(['codex', '--skills-dir', join(base, 'new/skills'), ...common])
  assert.equal(moved.status, 0, moved.stderr)
  assert.deepEqual(readdirSync(join(user, 'skills')), [])
  assert.ok(existsSync(user))
})

test('an --out folder whose name holds shell syntax does not run it', () => {
  const base = fresh()
  const out = join(base, 'o$(touch pwned)')
  assert.equal(run(['codex', '--out', out, '--date', DATE]).status, 0)
  const flow = spawnSync(join(out, 'home/bin/ndev-flow'), ['help'], { cwd: base, encoding: 'utf8' })
  assert.equal(flow.status, 0, flow.stderr)
  assert.ok(!existsSync(join(base, 'pwned')), 'the $(...) in the path ran')
})
