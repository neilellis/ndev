import { test } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const PLUGIN = resolve(HERE, '../../..')
const EXPORT = join(PLUGIN, 'scripts/export/export.mjs')
const DATE = '2026-11-17T12:00:00.000Z'

const run = (args, env = {}) => spawnSync('node', [EXPORT, ...args], { encoding: 'utf8', env: { ...process.env, ...env } })
const fresh = () => mkdtempSync(join(tmpdir(), 'ndev-export-'))
const exported = (harness = 'codex', extra = []) => {
  const out = fresh()
  const ran = run([harness, '--out', out, '--date', DATE, ...extra])
  assert.equal(ran.status, 0, `export exited ${ran.status}: ${ran.stderr}`)
  return { out, summary: JSON.parse(ran.stdout) }
}
const walk = dir => readdirSync(dir, { withFileTypes: true }).flatMap(e => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]))

test('each exported skill is renamed ndev-<name> and carries the generated stamp right after its frontmatter', () => {
  const { out, summary } = exported()
  const skills = readdirSync(join(out, 'skills'))
  assert.ok(skills.length > 20, `only ${skills.length} skills exported`)
  assert.ok(skills.every(name => name.startsWith('ndev-')), skills.join(', '))
  assert.ok(!skills.includes('ndev-for-codex'), 'the obsolete Codex linker must stay retired')
  for (const name of skills) {
    const text = readFileSync(join(out, 'skills', name, 'SKILL.md'), 'utf8')
    const lines = text.split('\n')
    const close = lines.indexOf('---', 1)
    assert.equal(lines[0], '---', `${name}: no frontmatter`)
    assert.match(lines.slice(0, close).join('\n'), new RegExp(`^name: ${name}$`, 'm'), `${name}: frontmatter name`)
    assert.match(lines[close + 1], /^<!-- Generated by ndev export for codex from ndev \d+\.\d+\.\d+ .* on 2026-11-17T12:00:00\.000Z\. Do not edit: run \/dev export codex to regenerate\. -->$/, `${name}: stamp`)
  }
  assert.equal(summary.skills, skills.length)
})

test('Claude-only references become paths and commands of the export', () => {
  const { out, summary } = exported()
  const home = join(out, 'home')
  assert.equal(summary.home, home)
  const files = walk(out).filter(f => /\.(md|sh|mjs|ts|json|toml|py)$/.test(f))
  for (const file of files) {
    const text = readFileSync(file, 'utf8')
    assert.ok(!text.includes('${CLAUDE_PLUGIN_ROOT}'), `${file} still names CLAUDE_PLUGIN_ROOT`)
    assert.ok(!/mcp__ndev__/.test(text), `${file} still names an mcp__ndev__ tool`)
  }
  const light = readFileSync(join(out, 'skills/ndev-work-light/SKILL.md'), 'utf8')
  assert.ok(light.includes(`${home}/bin/ndev-flow checkpoint`), 'checkpoint is a call of the flow CLI')
  assert.ok(light.includes('ndev-work-heavy'), 'ndev:work-heavy becomes ndev-work-heavy')
  assert.ok(!/\bndev:work-heavy\b/.test(light))
  assert.ok(existsSync(join(home, 'scripts/github/gh.sh')))
  assert.ok(existsSync(join(home, 'kb/workflow.md')))
})

test('a reference to a script inside a skill points to the exported skill folder', () => {
  const { out } = exported()
  const texts = walk(out).filter(f => f.endsWith('.md')).map(f => readFileSync(f, 'utf8')).join('\n')
  assert.ok(!texts.includes(`${join(out, 'home')}/skills/`), 'no path into a skills folder of the export home')
})

test('a link that leaves a skill points to the exported home or the exported sibling skill, and code keeps its text', () => {
  const { out } = exported()
  const review = readFileSync(join(out, 'skills/ndev-adversarial-review/SKILL.md'), 'utf8')
  const kb = review.match(/\]\(([^)]*kb\/verification-policy\.md)\)/)?.[1]
  assert.equal(kb, encodeURI(join(out, 'home/kb/verification-policy.md')))
  assert.ok(existsSync(decodeURI(kb)))
  const look = readFileSync(join(out, 'skills/ndev-ux-principles/references/generic-look.md'), 'utf8')
  assert.match(look, /\]\(\.\.\/\.\.\/ndev-motion\/SKILL\.md\)/)
  const plugin = fresh()
  mkdirSync(join(plugin, '.claude-plugin'))
  writeFileSync(join(plugin, '.claude-plugin/plugin.json'), '{"version":"0.0.1"}')
  mkdirSync(join(plugin, 'skills/sample'), { recursive: true })
  mkdirSync(join(plugin, 'agents'))
  mkdirSync(join(plugin, 'hooks/workflow'), { recursive: true })
  for (const file of ['machine.ts', 'change-types.ts', 'records.ts', 'session.ts']) copyFileSync(join(PLUGIN, 'hooks/workflow', file), join(plugin, 'hooks/workflow', file))
  writeFileSync(join(plugin, 'skills/sample/SKILL.md'), '---\nname: sample\ndescription: d\n---\nInline `[x](../../docs/a.md)`.\n\n```md\n[y](../../docs/b.md)\n```\n')
  const target = fresh()
  const ran = run(['codex', '--out', target, '--plugin-root', plugin, '--date', DATE])
  assert.equal(ran.status, 0, ran.stderr)
  const sample = readFileSync(join(target, 'skills/ndev-sample/SKILL.md'), 'utf8')
  assert.ok(sample.includes('`[x](../../docs/a.md)`') && sample.includes('[y](../../docs/b.md)'), sample)
})

test('the flow CLI is installed with the plugin state machine, unchanged but for import extensions', () => {
  const { out } = exported()
  const home = join(out, 'home')
  const bin = join(home, 'bin/ndev-flow')
  assert.ok(statSync(bin).mode & 0o100, 'bin/ndev-flow is executable')
  const machine = readFileSync(join(home, 'flow/workflow/machine.ts'), 'utf8')
  const original = readFileSync(join(PLUGIN, 'hooks/workflow/machine.ts'), 'utf8')
  assert.equal(machine, original.replaceAll("from './change-types'", "from './change-types.ts'"))
  const profile = JSON.parse(readFileSync(join(home, 'flow/profile.json'), 'utf8'))
  assert.equal(profile.name, 'codex')
  const ran = spawnSync(bin, ['help'], { encoding: 'utf8' })
  assert.equal(ran.status, 0, ran.stderr)
  assert.match(ran.stdout, /started/)
})

