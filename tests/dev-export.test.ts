import { expect, test } from './sdk-testing'

type On = Parameters<Parameters<typeof test>[1]>[1]
type Engine = Parameters<Parameters<typeof test>[1]>[0]

const ROOT = '/proj'
const SUMMARY = {
  harness: 'codex',
  home: '/home/user/.ndev-export/codex',
  skillsDir: '/home/user/.agents/skills',
  agentsDir: '/home/user/.codex/agents',
  skills: 41,
  agents: 7,
  files: 380,
  removed: 0,
  version: '0.35.0',
  generatedAt: '2026-11-17T12:00:00.000Z',
  flow: '/home/user/.ndev-export/codex/bin/ndev-flow',
  leftovers: { total: 12, file: '/home/user/.ndev-export/codex/leftovers.json', byConstruct: { 'Claude slash command': 9, 'Claude subagent call': 3 } },
  verify: 'codex debug prompt-input hi',
  verifyExpect: '- ndev-work-light: ',
  notes: 'Codex reads skills from ~/.agents/skills.',
}

function engine(on: On, result: { exitCode: number; stdout?: string; stderr?: string }) {
  const runs: string[][] = []
  on('command.register', (_, e) => ({ value: { command: e.name } }))
  on('tool.register', (_, e) => ({ value: { tool: `mcp__ndev__${e.name}` } }))
  on('clock.now', () => ({ value: 1_800_000_000_000 }))
  on('clock.every', () => new Promise(() => {}))
  on('session.start', (_, e) => ({ cwd: e.cwd }))
  on('session.id', () => ({ value: 'export-session' }))
  on('prompt.compose', () => ({ sections: [] }))
  on('env.get', () => ({ value: '/home/user' }))
  on('fs.exists', (_, e) => ({ value: e.path === `${ROOT}/.ndev.json` || e.path.startsWith('/home/user/dev-wiki') }))
  on('fs.read', (_, e) => ({ value: e.path === `${ROOT}/.ndev.json` ? JSON.stringify({ github: { repo: 'acme/widgets', board: null } }) : '' }))
  on('fs.write', () => ({ value: undefined }))
  on('ui.toast', () => ({ value: undefined }))
  on('ui.status', () => ({ value: undefined }))
  on('process.run', (_, e) => {
    const a = [...e.argv]
    runs.push(a)
    const out = a[0] === 'node' && String(a[1]).endsWith('scripts/export/export.mjs') ? result : { exitCode: 0, stdout: a[0] === 'git' ? `${ROOT}\n` : '' }
    return { value: { exitCode: out.exitCode, stdout: out.stdout ?? '', stderr: out.stderr ?? '', isStdoutTruncated: false, isStderrTruncated: false } }
  })
  return { runs }
}

const start = ($: Engine) => $.session.start({ cwd: ROOT, surface: 'terminal', isInteractive: true })
const dev = ($: Engine, args: string) => $.command.run({ command: 'dev', args })

test('/dev export codex runs the export script and briefs this session to adapt and verify the files', async ($, on) => {
  const w = engine(on, { exitCode: 0, stdout: JSON.stringify(SUMMARY) })
  await start($)

  const ran = await dev($, 'export codex')
  const call = w.runs.find(a => String(a[1]).endsWith('scripts/export/export.mjs'))
  expect(call?.slice(2)).toEqual(['codex'])
  expect(ran.text).toContain('/home/user/.ndev-export/codex')
  expect(ran.text).toContain('41 skills')
  expect(ran.text).toContain('12')
  const brief = (ran.context ?? []).join('\n')
  expect(brief).toContain('/home/user/.ndev-export/codex/leftovers.json')
  expect(brief).toContain('codex debug prompt-input')
  expect(brief).toContain('Codex reads skills from ~/.agents/skills.')
  expect(brief).toMatch(/generated stamp/i)
  expect(brief).toMatch(/do not touch|never change/i)
})

test('/dev export passes the flags through, and a dry run asks for no adapter', async ($, on) => {
  const w = engine(on, { exitCode: 0, stdout: JSON.stringify({ ...SUMMARY, dryRun: true }) })
  await start($)

  const ran = await dev($, 'export opencode2 --out /tmp/x --dry-run')
  expect(w.runs.find(a => String(a[1]).endsWith('scripts/export/export.mjs'))?.slice(2)).toEqual(['opencode2', '--out', '/tmp/x', '--dry-run'])
  expect(ran.text).toMatch(/dry run/i)
  expect(ran.context ?? []).toHaveLength(0)
})

test('/dev export with no harness names the known ones and runs nothing', async ($, on) => {
  const w = engine(on, { exitCode: 0, stdout: '{}' })
  await start($)

  const ran = await dev($, 'export')
  expect(ran.text).toMatch(/codex/)
  expect(ran.text).toMatch(/opencode/)
  expect(w.runs.some(a => String(a[1]).endsWith('scripts/export/export.mjs'))).toBe(false)
})

test('a failed export shows the exit code and what the script said, and asks for no adapter', async ($, on) => {
  engine(on, { exitCode: 3, stderr: 'ndev export: /home/user/.agents/skills/ndev-work-light/SKILL.md was not generated by ndev export. Repair: move it away.' })
  await start($)

  const ran = await dev($, 'export codex')
  expect(ran.text).toContain('exited 3')
  expect(ran.text).toContain('ndev-work-light/SKILL.md was not generated')
  expect(ran.text).toContain('Repair: move it away.')
  expect(ran.context ?? []).toHaveLength(0)
})

test('a failed export with long output keeps the first line of its error, not only the tail', async ($, on) => {
  const stderr = ['ndev export: /home/user/.agents/skills/ndev-x/SKILL.md was not generated by ndev export. Repair: move it away.', ...Array.from({ length: 30 }, (_, i) => `  also /home/user/.agents/skills/other-${i}/SKILL.md`)].join('\n')
  engine(on, { exitCode: 3, stdout: Array.from({ length: 30 }, (_, i) => `progress ${i}`).join('\n'), stderr })
  await start($)

  const ran = await dev($, 'export codex')
  expect(ran.text).toContain('ndev-x/SKILL.md was not generated')
  expect(ran.text).toContain('other-29/SKILL.md')
  expect(ran.text).not.toContain('progress 29')
})

test('the brief says that the manifest marks the files the export owns', async ($, on) => {
  engine(on, { exitCode: 0, stdout: JSON.stringify(SUMMARY) })
  await start($)

  const brief = ((await dev($, 'export codex')).context ?? []).join('\n')
  expect(brief).toMatch(/manifest\.json[^.]*tells the next export/)
})

test('/dev help lists /dev export', async ($, on) => {
  engine(on, { exitCode: 0 })
  await start($)
  expect((await dev($, 'help')).text).toMatch(/\/dev export <harness>/)
})
