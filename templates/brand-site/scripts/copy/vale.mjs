#!/usr/bin/env node
// Build the {{style}} Vale style from public/ds/copy/banned.json.
//   node scripts/copy/vale.mjs          check that public/ds/copy/vale is up to date
//   node scripts/copy/vale.mjs --write  write public/ds/copy/vale
// Banned words are warnings. Everything else is a suggestion. No rule is an error.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadRules } from './check-lib.mjs';

export const VALE_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../public/ds/copy/vale');
const SITE = '{{siteUrl}}';
const STRICT = ['documentation', 'technical-documentation', 'agent'];

// Vale uses Go regular expressions, which have no lookaround.
const RE2 = {
  may: '\\bmay\\b',
  semicolon: ';\\s',
};

const yamlString = (s) => `'${s.replace(/'/g, "''")}'`;
const header = (what) => `# ${what}\n# Generated by scripts/copy/vale.mjs from ${SITE}/ds/copy/banned.json. Do not edit.\n`;

function substitution(file, { what, level, message, words, ignorecase = true }) {
  const swap = words.map((w) => `  ${yamlString(RE2[w.term] ?? w.pattern)}: ${yamlString(w.instead)}`).join('\n');
  return [file, `${header(what)}extends: substitution\nmessage: ${yamlString(message)}\nlink: ${SITE}/copy/banned\nlevel: ${level}\nignorecase: ${ignorecase}\nnonword: true\naction:\n  name: replace\nswap:\n${swap}\n`];
}

function ruleName(id) {
  return id.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
}

// The strict rules are case-sensitive so 'May' in a date passes; every other word ignores case.
const strict = (words) => words.map((w) => (RE2[w.term] || /^\(\?i\)/.test(w.pattern) ? w : { ...w, pattern: `(?i)${w.pattern}` }));

export function buildVale(rules = loadRules()) {
  const plain = rules.words.filter((w) => !w.registers && !w.allow);
  const files = [
    substitution('Banned.yml', {
      what: 'Words with no place in plain English.',
      level: 'warning',
      message: "Avoid '%[2]s': %[1]s.",
      words: plain.filter((w) => w.level === 'ban'),
    }),
    substitution('Check.yml', {
      what: 'Ordinary words that are often misused. Keep the word only when it carries a fact.',
      level: 'suggestion',
      message: "Check '%[2]s': %[1]s.",
      words: plain.filter((w) => w.level === 'flag'),
    }),
    substitution('Jargon.yml', {
      what: 'Terms that are allowed in technical documentation only. Turn this rule off for technical documentation.',
      level: 'suggestion',
      message: "Check '%[2]s': %[1]s. This term is allowed in technical documentation.",
      words: rules.words.filter((w) => w.allow && !w.registers),
    }),
    substitution('Strict.yml', {
      what: `Simple English checks for ${STRICT.join(', ')} text. Turn this rule off for internal and marketing text.`,
      level: 'suggestion',
      message: "Simple English: '%[2]s'. %[1]s.",
      ignorecase: false,
      words: strict(rules.words.filter((w) => w.registers && !w.allow)),
    }),
    substitution('Formal.yml', {
      what: 'Simple English checks for documentation and agent text only. Turn this rule off for internal, marketing and technical documentation.',
      level: 'suggestion',
      message: "Simple English: '%[2]s'. %[1]s.",
      ignorecase: false,
      words: strict(rules.words.filter((w) => w.registers && w.allow)),
    }),
    ...rules.constructions.filter((c) => c.pattern).map((c) => [
      `${ruleName(c.id)}.yml`,
      `${header(c.name.replace(/[“”]/g, '"'))}extends: existence\nmessage: ${yamlString(`Pattern to avoid: ${c.name.replace(/[“”]/g, '"')}. ${c.fix}`.replace(/%/g, '%%'))}\nlink: ${SITE}/copy/banned\nlevel: suggestion\nignorecase: true\nnonword: true\ntokens:\n  - ${yamlString(c.pattern)}\n`,
    ]),
  ];
  for (const [name, body] of files) {
    if (/\(\?[=!<]/.test(body)) throw new Error(`${name} has a lookaround pattern, which Vale cannot read; add it to RE2 in scripts/copy/vale.mjs`);
  }
  const out = Object.fromEntries(files.map(([name, body]) => [`{{style}}/${name}`, Buffer.from(body)]));
  out['{{style}}.zip'] = zip(Object.entries(out));
  out['vale.ini'] = Buffer.from(ini());
  return out;
}

function ini() {
  return `# {{name}} copy rules for Vale (https://vale.sh).
# Save this file as .vale.ini at the top of your project, then run: vale sync
# Banned words are warnings. Everything else is a suggestion. No rule blocks.
# The rules come from ${SITE}/copy/banned.

StylesPath = .vale/styles
MinAlertLevel = suggestion
Packages = ${SITE}/ds/copy/vale/{{style}}.zip

[formats]
mdx = md

# Documentation and agent text: every rule.
[*.{md,mdx,txt,html}]
BasedOnStyles = {{style}}
# Quoted examples, such as “leverage synergies”, are not checked.
TokenIgnores = (“[^”]*”)

# Technical documentation: common technical terms are allowed.
[{README.md,docs/**}]
{{style}}.Jargon = NO
{{style}}.Formal = NO

# Marketing and internal text: no strict simple English checks.
# Change these paths to match your project.
[{content/**,marketing/**,internal/**}]
{{style}}.Strict = NO
{{style}}.Formal = NO
`;
}

// A minimal zip writer (stored, not compressed) with fixed timestamps, so the
// output is the same on every run.
const CRC = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function zip(entries) {
  const all = [['{{style}}/', Buffer.alloc(0)], ...entries];
  const local = [];
  const central = [];
  let offset = 0;
  for (const [name, data] of all) {
    const n = Buffer.from(name);
    const crc = crc32(data);
    const head = Buffer.alloc(30);
    head.writeUInt32LE(0x04034b50, 0); head.writeUInt16LE(20, 4); head.writeUInt16LE(0x0800, 6);
    head.writeUInt16LE(0, 8); head.writeUInt16LE(0, 10); head.writeUInt16LE(0x21, 12);
    head.writeUInt32LE(crc, 14); head.writeUInt32LE(data.length, 18); head.writeUInt32LE(data.length, 22);
    head.writeUInt16LE(n.length, 26); head.writeUInt16LE(0, 28);
    local.push(head, n, data);
    const cen = Buffer.alloc(46);
    cen.writeUInt32LE(0x02014b50, 0); cen.writeUInt16LE(20, 4); cen.writeUInt16LE(20, 6); cen.writeUInt16LE(0x0800, 8);
    cen.writeUInt16LE(0, 10); cen.writeUInt16LE(0, 12); cen.writeUInt16LE(0x21, 14);
    cen.writeUInt32LE(crc, 16); cen.writeUInt32LE(data.length, 20); cen.writeUInt32LE(data.length, 24);
    cen.writeUInt16LE(n.length, 28); cen.writeUInt32LE(name.endsWith('/') ? 0x10 : 0, 38); cen.writeUInt32LE(offset, 42);
    central.push(cen, n);
    offset += 30 + n.length + data.length;
  }
  const cd = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(all.length, 8); end.writeUInt16LE(all.length, 10);
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...local, cd, end]);
}

// Paths in public/ds/copy/vale that differ from a fresh build.
export function staleValeFiles(built = buildVale()) {
  return Object.entries(built)
    .filter(([name, data]) => { const p = path.join(VALE_DIR, name); return !existsSync(p) || !readFileSync(p).equals(data); })
    .map(([name]) => name);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const built = buildVale();
  if (process.argv.includes('--write')) {
    for (const [name, data] of Object.entries(built)) {
      mkdirSync(path.dirname(path.join(VALE_DIR, name)), { recursive: true });
      writeFileSync(path.join(VALE_DIR, name), data);
    }
    console.log(`vale: wrote ${Object.keys(built).length} files to public/ds/copy/vale`);
  } else {
    const stale = staleValeFiles(built);
    if (stale.length) { console.error(`vale: out of date: ${stale.join(', ')}. Run node scripts/copy/vale.mjs --write`); process.exit(1); }
    console.log('vale: public/ds/copy/vale is up to date');
  }
}
